// Netlify build step: writes web/_redirects so the site proxies the API (and résumé share pages) to the computer
// running the CareerPilot server, and fills the site's address into index.html, robots.txt and sitemap.xml.
// Everything else is served as static files. No dependencies; runs with Netlify's built-in Node.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const backend = (process.env.CAREERPILOT_BACKEND_URL || '').trim().replace(/\/+$/, '');
if (!/^https?:\/\/[^/\s]+$/.test(backend)) {
  console.error(
    '\nCAREERPILOT_BACKEND_URL is missing or not a plain origin.\n' +
    'In Netlify, open Site configuration → Environment variables and set it to the HTTPS address of the computer\n' +
    'running the CareerPilot server, for example https://api.example.com (no path, no trailing slash).\n',
  );
  process.exit(1);
}
if (backend.startsWith('http://')) console.warn('Warning: CAREERPILOT_BACKEND_URL is not HTTPS; sign-in cookies and data travel unencrypted between Netlify and the server.');

const rules = [
  '# Generated by netlify/build.mjs at deploy time - do not edit or commit.',
  '# API and résumé share pages come from the CareerPilot server; everything else is this static site.',
  '# The app has no other pages (its screens live behind #/…), so unknown paths get the real 404 page.',
  `/api/*  ${backend}/api/:splat  200!`,
  `/r/*    ${backend}/r/:splat    200!`,
  '',
].join('\n');
writeFileSync(new URL('../web/_redirects', import.meta.url), rules);
console.log(`web/_redirects written: API proxied to ${backend}`);

// ---- search engines: absolute addresses in the page, robots.txt and sitemap.xml
// CAREERPILOT_PUBLIC_URL wins (set it to your custom domain); otherwise Netlify's own URL for this site.
const site = (process.env.CAREERPILOT_PUBLIC_URL || process.env.URL || '').trim().replace(/\/+$/, '');
if (!site) console.warn('Warning: no site address known (CAREERPILOT_PUBLIC_URL or URL); canonical and sitemap links will be relative.');
const verification = (process.env.CAREERPILOT_GOOGLE_SITE_VERIFICATION || process.env.GOOGLE_SITE_VERIFICATION || '').trim().replace(/[^A-Za-z0-9_-]/g, '');
const preview = !!process.env.CONTEXT && process.env.CONTEXT !== 'production';   // deploy previews and branch deploys stay out of Google
const today = new Date().toISOString().slice(0, 10);
const webDir = new URL('../web/', import.meta.url);
const pages = readdirSync(webDir, { recursive: true }).map(String).filter(f => f.endsWith('.html') && !f.startsWith('assets'));
const extra = [];
if (verification) extra.push(`<meta name="google-site-verification" content="${verification}">`);
if (preview) extra.push('<meta name="robots" content="noindex">');
for (const name of [...pages, 'robots.txt', 'sitemap.xml']) {
  const file = new URL(name.replaceAll('\\', '/'), webDir);
  const text = readFileSync(file, 'utf8').replaceAll('__PUBLIC_URL__', site).replaceAll('__LASTMOD__', today).replace('<!--seo-extra-->', extra.join('\n'));
  writeFileSync(file, text);
}
console.log(`site address ${site || '(relative)'} written into ${pages.length} pages, robots.txt and sitemap.xml${verification ? ' with the Search Console tag' : ''}${preview ? ' (noindex: not a production deploy)' : ''}`);
