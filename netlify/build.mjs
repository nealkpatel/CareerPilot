// Netlify build step: writes web/_redirects so the site proxies the API (and résumé share pages) to the computer
// running the CareerPilot server. Everything else is served as static files, with index.html for the single-page app.
// No dependencies; runs with Netlify's built-in Node.
import { writeFileSync } from 'node:fs';

const backend = (process.env.CAREERPILOT_BACKEND_URL || '').trim().replace(/\/+$/, '');
if (!/^https?:\/\/[^/\s]+$/.test(backend)) {
  console.error(
    '\nCAREERPILOT_BACKEND_URL is missing or not a plain origin.\n' +
    'In Netlify, open Site configuration → Environment variables and set it to the HTTPS address of the computer\n' +
    'running the CareerPilot server, for example https://api.example.com (no path, no trailing slash).\n',
  );
  process.exit(1);
}
if (backend.startsWith('http://')) console.warn('Warning: CAREERPILOT_BACKEND_URL is not HTTPS; sign-in cookies and data travel unencrypted between Netlify and the server.');

const rules = [
  '# Generated by netlify/build.mjs at deploy time - do not edit or commit.',
  '# API and résumé share pages come from the CareerPilot server; everything else is this static site.',
  `/api/*  ${backend}/api/:splat  200!`,
  `/r/*    ${backend}/r/:splat    200!`,
  '/*      /index.html            200',
  '',
].join('\n');
writeFileSync(new URL('../web/_redirects', import.meta.url), rules);
console.log(`web/_redirects written: API proxied to ${backend}`);
