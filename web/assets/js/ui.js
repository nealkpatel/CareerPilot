export function logo(name, size = 36, src = {}) {
  const qs = src.jobId ? `job_id=${src.jobId}` : `company=${encodeURIComponent(name || '')}${src.url ? `&url=${encodeURIComponent(src.url)}` : ''}`;
  return html`<div class="co-logo" style="background:${colorFor(name)};width:${size}px;height:${size}px;font-size:${Math.round(size / 2.6)}px">${initials(name)}${name ? raw(`<img src="/api/logo?${esc(qs)}&amp;v=3" alt="" decoding="async" onload="this.parentNode.classList.add('has-img')" onerror="this.remove()">`) : ''}</div>`;
}

