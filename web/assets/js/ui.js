export function debounce(fn, ms = 300) {
  let t;
  return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
}

// ---------------------------------------------------------------- toasts
export function toast(msg, kind = 'ok') {
  const el = document.createElement('div');
  el.className = `toast ${kind}`;
  el.innerHTML = `${icon(kind === 'error' ? 'alert' : 'checkCircle')}<span>${esc(msg)}</span>`;
  document.getElementById('toasts').appendChild(el);
  setTimeout(() => { el.style.transition = 'opacity .3s'; el.style.opacity = '0'; }, 3600);
  setTimeout(() => el.remove(), 4000);
}
export const toastError = (e) => toast(e?.message || String(e), 'error');

export async function copyText(text, msg = 'Copied to clipboard') {
  try { await navigator.clipboard.writeText(text); toast(msg); }
  catch { toast('Copy failed — select and copy manually.', 'error'); }
}

// ---------------------------------------------------------------- modals
export function modal({ title, body, foot = '', size = '', onMount, drawer = false }) {
  const ov = document.createElement('div');
  ov.className = 'overlay' + (drawer ? ' drawer-overlay' : '');
  ov.innerHTML = `<div class="${drawer ? 'drawer' : 'modal ' + size}" role="dialog" aria-modal="true">
    <div class="modal-head"><h2 class="grow truncate">${esc(title)}</h2><button class="btn ghost icon" data-close aria-label="Close">${icon('x')}</button></div>
    <div class="modal-body">${body}</div>${foot ? `<div class="modal-foot">${foot}</div>` : ''}</div>`;
  const close = () => { ov.remove(); document.removeEventListener('keydown', onKey); };
  const onKey = (e) => { if (e.key === 'Escape') close(); };
  ov.addEventListener('mousedown', (e) => { if (e.target === ov) close(); });
  ov.querySelectorAll('[data-close]').forEach(b => b.addEventListener('click', close));
  document.addEventListener('keydown', onKey);
  document.body.appendChild(ov);
  const api = { el: ov, close, $: (s) => ov.querySelector(s), $$: (s) => Array.from(ov.querySelectorAll(s)) };
  onMount?.(api);
  return api;
}

export function confirmDialog({ title = 'Are you sure?', message = '', confirm = 'Confirm', danger = false }) {
  return new Promise((resolve) => {
    let done = false;
    const m = modal({
      title,
      body: `<p style="color:var(--text-2)">${message}</p>`,
      foot: `<button class="btn" data-close>Cancel</button><button class="btn ${danger ? 'danger' : 'primary'}" data-ok>${esc(confirm)}</button>`,
    });
    m.$('[data-ok]').addEventListener('click', () => { done = true; m.close(); resolve(true); });
    const obs = new MutationObserver(() => { if (!document.body.contains(m.el)) { obs.disconnect(); if (!done) resolve(false); } });
    obs.observe(document.body, { childList: true });
  });
}

export function busy(btn, on, label) {
  if (!btn) return;
  if (on) { btn.dataset.html = btn.innerHTML; btn.disabled = true; btn.innerHTML = `<span class="spinner"></span>${label ? esc(label) : ''}`; }
  else { btn.disabled = false; if (btn.dataset.html) btn.innerHTML = btn.dataset.html; }
}

